# BUILD TELEGRAM APPLICATION
# ============================================================

def build_application():
    """
    Create the Telegram application and register handlers.

    IMPORTANT:
    This function does NOT start polling.
    FastAPI will manage the Telegram application
    lifecycle because we are using webhook mode.
    """

    if not TELEGRAM_BOT_TOKEN:

        raise RuntimeError(
            "TELEGRAM_BOT_TOKEN is not configured."
        )

    app = (
        Application
        .builder()
        .token(TELEGRAM_BOT_TOKEN)
        .build()
    )

    # --------------------------------------------------------
    # /start
    # --------------------------------------------------------

    app.add_handler(
        CommandHandler(
            "start",
            start,
        )
    )

    # --------------------------------------------------------
    # /papers
    # --------------------------------------------------------

    app.add_handler(
        CommandHandler(
            "papers",
            papers,
        )
    )

    # --------------------------------------------------------
    # Paper selection button
    # --------------------------------------------------------

    app.add_handler(
        CallbackQueryHandler(
            select_paper,
            pattern=r"^paper:",
        )
    )

    # --------------------------------------------------------
    # Natural-language questions
    # --------------------------------------------------------

    app.add_handler(
        MessageHandler(
            filters.TEXT
            & ~filters.COMMAND,
            question,
        )
    )

    return app


# ============================================================
# PROCESS TELEGRAM WEBHOOK UPDATE
# ============================================================

async def handle_update(
    telegram_app,
    update_data,
):
    """
    Convert Telegram JSON into a python-telegram-bot Update
    and pass it to the registered handlers.
    """

    update = Update.de_json(
        update_data,
        telegram_app.bot,
    )

    if update is None:
        return

    await telegram_app.process_update(
        update
    )



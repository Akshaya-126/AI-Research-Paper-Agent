# TELEGRAM SESSION
# ============================================================

def set_active_paper(chat_id, paper_id):
    """
    Store the paper currently selected by a Telegram user.
    """

    (
        supabase
        .table("telegram_sessions")
        .upsert(
            {
                "chat_id": chat_id,
                "paper_id": paper_id,
            },
            on_conflict="chat_id",
        )
        .execute()
    )


def get_active_paper(chat_id):
    """
    Retrieve the paper currently selected by a Telegram user.
    """

    response = (
        supabase
        .table("telegram_sessions")
        .select("paper_id")
        .eq("chat_id", chat_id)
        .limit(1)
        .execute()
    )

    if not response.data:
        return None

    return response.data[0].get("paper_id")


# ============================================================
# SOURCE FORMATTING
# ============================================================

def format_sources(sources):
    """
    Convert RAG source metadata into a readable Telegram message.
    """

    if not sources:
        return ""

    lines = []
    seen = set()

    for source in sources:

        key = (
            source.get("section"),
            source.get("subsection"),
            source.get("page_start"),
            source.get("page_end"),
        )

        if key in seen:
            continue

        seen.add(key)

        section = source.get("section") or "Unknown"

        subsection = source.get("subsection")

        if subsection:
            section += f" → {subsection}"

        page_start = source.get("page_start")
        page_end = source.get("page_end")

        if page_start and page_end:

            if page_start == page_end:
                pages = f"p. {page_start}"
            else:
                pages = f"pp. {page_start}–{page_end}"

            lines.append(
                f"• {section} ({pages})"
            )

        elif page_start:

            lines.append(
                f"• {section} (p. {page_start})"
            )

        else:

            lines.append(
                f"• {section}"
            )

    if not lines:
        return ""

    return (
        "Sources:\n"
        + "\n".join(lines)
    )


# ============================================================
# CLEAN GEMINI ANSWER
# ============================================================

def clean_llm_answer(text):
    """
    Remove internal source markers generated by the RAG prompt.
    """

    if not text:
        return ""

    # Remove markers such as:
    # [SOURCE 1]
    # [SOURCE 1, SOURCE 2]

    text = re.sub(
        r"\[SOURCE\s+\d+(?:\s*,\s*SOURCE\s+\d+)*\]",
        "",
        text,
        flags=re.IGNORECASE,
    )

    # Remove an existing Sources section.
    text = re.sub(
        r"\n+\s*Sources:\s*(?:\n[-•].*)*$",
        "",
        text,
        flags=re.IGNORECASE,
    )

    # Remove trailing spaces before newlines.
    text = re.sub(
        r"[ \t]+\n",
        "\n",
        text,
    )

    # Avoid excessive blank lines.
    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text,
    )

    return text.strip()


# ============================================================
# LONG TELEGRAM MESSAGE HANDLER
# ============================================================

async def send_long_message(message, text):
    """
    Telegram messages have a character limit.
    Split long RAG answers safely.
    """

    if not text:
        return

    max_length = 4000

    if len(text) <= max_length:

        await message.reply_text(text)

        return

    parts = []

    while text:

        if len(text) <= max_length:

            parts.append(text)

            break

        split_at = text.rfind(
            "\n",
            0,
            max_length,
        )

        if split_at <= 0:

            split_at = max_length

        parts.append(
            text[:split_at]
        )

        text = text[split_at:].lstrip()

    for part in parts:

        await message.reply_text(part)



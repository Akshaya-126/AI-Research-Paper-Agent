# /START
# ============================================================

async def start(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):
    """
    Register the Telegram user for paper notifications.
    """

    chat = update.effective_chat
    user = update.effective_user

    if not chat:
        return

    try:

        register_subscriber(
            chat_id=chat.id,
            username=(
                user.username
                if user
                else None
            ),
            first_name=(
                user.first_name
                if user
                else None
            ),
        )

        if update.message:

            await update.message.reply_text(
                "🔬 ResearchX AI\n\n"
                "✅ You are now registered for new AI "
                "research paper notifications.\n\n"
                "When a new paper arrives, tap "
                "📖 Ask about this paper to start asking "
                "questions about it.\n\n"
                "You can also use /papers to browse "
                "previous papers."
            )

    except Exception:

        logger.exception(
            "Subscriber registration failed"
        )

        if update.message:

            await update.message.reply_text(
                "🔬 ResearchX AI\n\n"
                "I couldn't register you for notifications "
                "right now.\n\n"
                "Please try /start again."
            )


# ============================================================
# /PAPERS
# ============================================================

async def papers(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):
    """
    Display previously ingested research papers.
    """

    if not update.message:
        return

    try:

        response = (
            supabase
            .table("papers")
            .select(
                "paper_id,title,created_at"
            )
            .order(
                "created_at",
                desc=True,
            )
            .limit(50)
            .execute()
        )

        papers_data = response.data or []

        if not papers_data:

            await update.message.reply_text(
                "📚 No papers are currently ingested."
            )

            return

        keyboard = []

        for paper in papers_data:

            paper_id = paper.get(
                "paper_id"
            )

            title = paper.get(
                "title",
                "Untitled paper",
            )

            if not paper_id:
                continue

            keyboard.append(
                [
                    InlineKeyboardButton(
                        text=f"📖 {title}",
                        callback_data=(
                            f"paper:{paper_id}"
                        ),
                    )
                ]
            )

        if not keyboard:

            await update.message.reply_text(
                "📚 No selectable papers found."
            )

            return

        reply_markup = InlineKeyboardMarkup(
            keyboard
        )

        await update.message.reply_text(
            "📚 Your Research Papers\n\n"
            "Tap a paper to select it and start "
            "asking questions:",
            reply_markup=reply_markup,
        )

    except Exception as exc:

        logger.exception(
            "Failed to retrieve papers"
        )

        await update.message.reply_text(
            "Sorry, I couldn't retrieve the "
            "paper list right now.\n\n"
            f"Error: {exc}"
        )


# ============================================================
# PAPER SELECTION
# ============================================================

async def select_paper(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):
    """
    Handle the button used to select a paper.
    """

    query = update.callback_query

    if not query:
        return

    await query.answer()

    data = query.data or ""

    if not data.startswith("paper:"):
        return

    paper_id = data[
        len("paper:"):
    ].strip()

    if not paper_id:

        if query.message:

            await query.message.reply_text(
                "❌ Invalid paper selection."
            )

        return

    chat = update.effective_chat

    if not chat:
        return

    chat_id = chat.id

    # --------------------------------------------------------
    # Verify that the selected paper exists.
    # --------------------------------------------------------

    try:

        response = (
            supabase
            .table("papers")
            .select(
                "paper_id,title"
            )
            .eq(
                "paper_id",
                paper_id,
            )
            .limit(1)
            .execute()
        )

        if not response.data:

            if query.message:

                await query.message.reply_text(
                    "❌ This paper could not be found."
                )

            return

        paper = response.data[0]

    except Exception:

        logger.exception(
            "Failed to verify selected paper"
        )

        if query.message:

            await query.message.reply_text(
                "❌ I couldn't verify that paper right now."
            )

        return

    # --------------------------------------------------------
    # Save selected paper in Supabase.
    # --------------------------------------------------------

    try:

        set_active_paper(
            chat_id,
            paper_id,
        )

        logger.info(
            "Selected paper for chat %s: %s",
            chat_id,
            paper_id,
        )

    except Exception:

        logger.exception(
            "Failed to store Telegram session"
        )

        if query.message:

            await query.message.reply_text(
                "❌ I couldn't save your paper selection "
                "right now. Please try again."
            )

        return

    # --------------------------------------------------------
    # Confirm selection.
    # --------------------------------------------------------

    if query.message:

        await query.message.reply_text(
            "✅ Paper selected!\n\n"
            f"📖 {paper['title']}\n\n"
            "You can now ask me anything about this paper."
        )


# ============================================================
# NATURAL LANGUAGE QUESTION
# ============================================================

async def question(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):
    """
    Handle arbitrary questions about the selected paper.
    """

    if not update.message:
        return

    chat = update.effective_chat

    if not chat:
        return

    chat_id = chat.id

    # --------------------------------------------------------
    # Get currently selected paper.
    # --------------------------------------------------------

    try:

        paper_id = get_active_paper(
            chat_id
        )

    except Exception:

        logger.exception(
            "Failed to retrieve Telegram session"
        )

        await update.message.reply_text(
            "Sorry, I couldn't retrieve your selected "
            "paper right now.\n\n"
            "Please select the paper again using /papers."
        )

        return

    # --------------------------------------------------------
    # No paper selected.
    # --------------------------------------------------------

    if not paper_id:

        await update.message.reply_text(
            "📖 Please select a paper first.\n\n"
            "Use /papers and tap the paper you "
            "want to ask about."
        )

        return

    # --------------------------------------------------------
    # Get user's question.
    # --------------------------------------------------------

    q = (
        update.message.text or ""
    ).strip()

    if not q:
        return

    # --------------------------------------------------------
    # Show processing message.
    # --------------------------------------------------------

    processing_message = (
        await update.message.reply_text(
            "🔎 Searching the paper and "
            "generating an answer..."
        )
    )

    logger.info(
        "Question from chat %s | paper=%s | question=%s",
        chat_id,
        paper_id,
        q,
    )

    # --------------------------------------------------------
    # RAG + Gemini.
    # --------------------------------------------------------

    try:

        result = answer_question(
            q,
            paper_id,
        )

        # ----------------------------------------------------
        # Clean generated answer.
        # ----------------------------------------------------

        text = clean_llm_answer(
            result.get(
                "answer",
                "",
            )
        )

        # ----------------------------------------------------
        # Format sources.
        # ----------------------------------------------------

        sources = format_sources(
            result.get(
                "sources",
                [],
            )
        )

        # ----------------------------------------------------
        # Add sources to final answer.
        # ----------------------------------------------------

        if sources:

            text = re.sub(
                r"\n+\s*Sources:\s*(?:\n[-•].*)*$",
                "",
                text,
                flags=re.IGNORECASE,
            ).strip()

            text = (
                f"{text}\n\n"
                f"{sources}"
            )

        # ----------------------------------------------------
        # Fallback answer.
        # ----------------------------------------------------

        if not text:

            text = (
                "I could not generate an answer "
                "from the retrieved paper context."
            )

        # ----------------------------------------------------
        # Send answer.
        # ----------------------------------------------------

        await send_long_message(
            update.message,
            text,
        )

        # ----------------------------------------------------
        # Remove processing message.
        # ----------------------------------------------------

        try:

            await processing_message.delete()

        except Exception:

            pass

    except Exception as exc:

        logger.exception(
            "RAG error"
        )

        try:

            await processing_message.delete()

        except Exception:

            pass

        await update.message.reply_text(
            "Sorry, I couldn't complete "
            "that request.\n\n"
            f"Error: {exc}"
        )


